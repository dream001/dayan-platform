FROM sys_role r
CROSS JOIN sys_menu_permission p
WHERE r.code = 'SUPER_ADMIN'
  AND p.code IN (
      'basic:model:view',
      'basic:model:create',
      'basic:model:update',
      'basic:model:delete',
      'basic:model:test'
  )
ON CONFLICT DO NOTHING;

