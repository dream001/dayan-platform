CREATE TABLE ai_model (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manufacturer VARCHAR(100) NOT NULL,
    name VARCHAR(160) NOT NULL,
    access_address VARCHAR(500) NOT NULL,
    model_url VARCHAR(1000) NOT NULL,
    model_type VARCHAR(32) NOT NULL,
    access_key_ciphertext TEXT,
    secret_key_ciphertext TEXT,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    last_test_status VARCHAR(16) NOT NULL DEFAULT 'NEVER',
    last_test_message VARCHAR(500),
    last_test_latency_ms BIGINT,
    last_tested_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_model_manufacturer_name UNIQUE (manufacturer, name),
    CONSTRAINT ck_ai_model_manufacturer_not_blank CHECK (btrim(manufacturer) <> ''),
    CONSTRAINT ck_ai_model_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_ai_model_access_address_not_blank CHECK (btrim(access_address) <> ''),
    CONSTRAINT ck_ai_model_url_not_blank CHECK (btrim(model_url) <> ''),
    CONSTRAINT ck_ai_model_type CHECK (
        model_type IN ('CHAT', 'EMBEDDING', 'MULTIMODAL', 'RERANK', 'IMAGE', 'AUDIO')
    ),
    CONSTRAINT ck_ai_model_test_status CHECK (
        last_test_status IN ('NEVER', 'SUCCESS', 'FAILED')
    ),
    CONSTRAINT ck_ai_model_test_latency CHECK (
        last_test_latency_ms IS NULL OR last_test_latency_ms >= 0
    )
);

CREATE INDEX idx_ai_model_type_enabled
    ON ai_model (model_type, enabled, updated_at DESC);

