CREATE TABLE workflow_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_id BIGINT NOT NULL,
    dataset_id BIGINT NOT NULL,
    stage VARCHAR(32) NOT NULL DEFAULT 'MATCHING',
    status VARCHAR(16) NOT NULL DEFAULT 'QUEUED',
    progress INTEGER NOT NULL DEFAULT 0,
    trigger_type VARCHAR(16) NOT NULL DEFAULT 'MANUAL',
    steps_snapshot_json TEXT NOT NULL DEFAULT '[]',
    error_message VARCHAR(2000),
    created_by BIGINT NOT NULL,
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_workflow_run_definition FOREIGN KEY (workflow_id)
        REFERENCES workflow_definition (id) ON DELETE RESTRICT,
    CONSTRAINT fk_workflow_run_dataset FOREIGN KEY (dataset_id)
        REFERENCES data_dataset (id) ON DELETE RESTRICT,
    CONSTRAINT fk_workflow_run_creator FOREIGN KEY (created_by)
        REFERENCES sys_user (id) ON DELETE RESTRICT,
    CONSTRAINT ck_workflow_run_stage CHECK (
        stage IN ('MATCHING', 'NORMALIZING', 'PROCESSING', 'QUALITY', 'ANNOTATION', 'DELIVERY')
    ),
    CONSTRAINT ck_workflow_run_status CHECK (
        status IN ('QUEUED', 'RUNNING', 'COMPLETED', 'FAILED', 'CANCELLED')
    ),
    CONSTRAINT ck_workflow_run_progress CHECK (progress BETWEEN 0 AND 100),
    CONSTRAINT ck_workflow_run_trigger CHECK (trigger_type IN ('AUTO', 'MANUAL', 'TEST')),
    CONSTRAINT ck_workflow_run_steps CHECK (
        steps_snapshot_json::jsonb IS NOT NULL
        AND jsonb_typeof(steps_snapshot_json::jsonb) = 'array'
    )
);

CREATE INDEX idx_workflow_run_recent
    ON workflow_run (status, created_at DESC, id DESC);
CREATE INDEX idx_workflow_run_dataset
    ON workflow_run (dataset_id, created_at DESC, id DESC);

