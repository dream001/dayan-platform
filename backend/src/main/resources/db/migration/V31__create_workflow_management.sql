CREATE TABLE workflow_match_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    description VARCHAR(500),
    scope VARCHAR(16) NOT NULL,
    project_id BIGINT,
    priority INTEGER NOT NULL DEFAULT 100,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    logic_operator VARCHAR(8) NOT NULL DEFAULT 'AND',
    conditions_json TEXT NOT NULL DEFAULT '[]',
    creator_id BIGINT NOT NULL,
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_workflow_match_project FOREIGN KEY (project_id)
        REFERENCES basic_project (id) ON DELETE CASCADE,
    CONSTRAINT fk_workflow_match_creator FOREIGN KEY (creator_id)
        REFERENCES sys_user (id) ON DELETE RESTRICT,
    CONSTRAINT ck_workflow_match_name CHECK (btrim(name) <> ''),
    CONSTRAINT ck_workflow_match_scope CHECK (scope IN ('GLOBAL', 'PROJECT')),
    CONSTRAINT ck_workflow_match_project_scope CHECK (
        (scope = 'GLOBAL' AND project_id IS NULL)
        OR (scope = 'PROJECT' AND project_id IS NOT NULL)
    ),
    CONSTRAINT ck_workflow_match_logic CHECK (logic_operator IN ('AND', 'OR')),
    CONSTRAINT ck_workflow_match_conditions CHECK (
        conditions_json::jsonb IS NOT NULL
        AND jsonb_typeof(conditions_json::jsonb) = 'array'
    )
);

CREATE INDEX idx_workflow_match_active
    ON workflow_match_rule (scope, project_id, enabled, priority, id)
    WHERE deleted_at IS NULL;

