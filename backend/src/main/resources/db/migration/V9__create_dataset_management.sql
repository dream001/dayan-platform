CREATE TABLE data_dataset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    file_id BIGINT NOT NULL,
    thumbnail_object_key VARCHAR(1024),
    data_type VARCHAR(16) NOT NULL,
    size_bytes BIGINT NOT NULL,
    duration_seconds NUMERIC(12, 3),
    annotation_status VARCHAR(16) NOT NULL DEFAULT 'UNASSIGNED',
    project_id BIGINT,
    task_id BIGINT,
    robot_code VARCHAR(128),
    collector_id BIGINT,
    source_task_code VARCHAR(128),
    uploader_id BIGINT NOT NULL,
    metadata_status VARCHAR(16) NOT NULL DEFAULT 'READY',
    open_shared BOOLEAN NOT NULL DEFAULT FALSE,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_data_dataset_file FOREIGN KEY (file_id)
        REFERENCES file_metadata (id) ON DELETE RESTRICT,
    CONSTRAINT fk_data_dataset_project FOREIGN KEY (project_id)
        REFERENCES basic_project (id) ON DELETE SET NULL,
    CONSTRAINT fk_data_dataset_collector FOREIGN KEY (collector_id)
        REFERENCES sys_user (id) ON DELETE SET NULL,
    CONSTRAINT fk_data_dataset_uploader FOREIGN KEY (uploader_id)
        REFERENCES sys_user (id) ON DELETE RESTRICT,
    CONSTRAINT ck_data_dataset_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_data_dataset_type
        CHECK (data_type IN ('VIDEO', 'AUDIO', 'MCAP')),
    CONSTRAINT ck_data_dataset_size CHECK (size_bytes >= 0),
    CONSTRAINT ck_data_dataset_duration
        CHECK (duration_seconds IS NULL OR duration_seconds >= 0),
    CONSTRAINT ck_data_dataset_annotation_status
        CHECK (annotation_status IN ('UNASSIGNED', 'ASSIGNED', 'COMPLETED')),
    CONSTRAINT ck_data_dataset_metadata
        CHECK (metadata_status IN ('PENDING', 'PROCESSING', 'READY', 'FAILED')),
    CONSTRAINT ck_data_dataset_deleted CHECK (deleted_at IS NULL OR deleted = TRUE)
);

CREATE UNIQUE INDEX uk_data_dataset_active_name
    ON data_dataset (lower(name))
    WHERE deleted = FALSE;

CREATE INDEX idx_data_dataset_list
    ON data_dataset (deleted, annotation_status, updated_at DESC, id DESC);
CREATE INDEX idx_data_dataset_uploader
    ON data_dataset (uploader_id, id)
    WHERE deleted = FALSE;
CREATE INDEX idx_data_dataset_project
    ON data_dataset (project_id, id)
    WHERE deleted = FALSE;
CREATE INDEX idx_data_dataset_collector
    ON data_dataset (collector_id)
    WHERE deleted = FALSE;
CREATE INDEX idx_data_dataset_task
    ON data_dataset (task_id)
    WHERE deleted = FALSE;

CREATE TABLE data_dataset_tag (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_data_dataset_tag_name UNIQUE (name),
    CONSTRAINT ck_data_dataset_tag_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE data_dataset_tag_rel (
    dataset_id BIGINT NOT NULL,
    tag_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (dataset_id, tag_id),
    CONSTRAINT fk_data_dataset_tag_rel_dataset FOREIGN KEY (dataset_id)
        REFERENCES data_dataset (id) ON DELETE CASCADE,
    CONSTRAINT fk_data_dataset_tag_rel_tag FOREIGN KEY (tag_id)
        REFERENCES data_dataset_tag (id) ON DELETE CASCADE
);

CREATE INDEX idx_data_dataset_tag_rel_tag
    ON data_dataset_tag_rel (tag_id);

CREATE TABLE data_annotation_task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'OPEN',
    dataset_count INTEGER NOT NULL DEFAULT 0,
    creator_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_data_annotation_task_creator FOREIGN KEY (creator_id)
        REFERENCES sys_user (id) ON DELETE RESTRICT,
    CONSTRAINT ck_data_annotation_task_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_data_annotation_task_status
        CHECK (status IN ('OPEN', 'COMPLETED'))
);

ALTER TABLE data_dataset
    ADD CONSTRAINT fk_data_dataset_task FOREIGN KEY (task_id)
        REFERENCES data_annotation_task (id) ON DELETE SET NULL;

CREATE TABLE data_annotation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id BIGINT NOT NULL,
    task_id BIGINT,
    annotator_id BIGINT,
    content_text TEXT,
    covered_duration_seconds NUMERIC(12, 3),
    is_valid BOOLEAN NOT NULL DEFAULT TRUE,
    is_qualified BOOLEAN NOT NULL DEFAULT FALSE,
    reviewed BOOLEAN NOT NULL DEFAULT FALSE,
    invalid_collect BOOLEAN NOT NULL DEFAULT FALSE,
    semantic_error BOOLEAN NOT NULL DEFAULT FALSE,
    semantic_corrected BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_data_annotation_dataset FOREIGN KEY (dataset_id)
        REFERENCES data_dataset (id) ON DELETE CASCADE,
    CONSTRAINT fk_data_annotation_task FOREIGN KEY (task_id)
        REFERENCES data_annotation_task (id) ON DELETE SET NULL,
    CONSTRAINT fk_data_annotation_annotator FOREIGN KEY (annotator_id)
        REFERENCES sys_user (id) ON DELETE SET NULL,
    CONSTRAINT ck_data_annotation_covered
        CHECK (covered_duration_seconds IS NULL OR covered_duration_seconds >= 0)
);

CREATE INDEX idx_data_annotation_dataset ON data_annotation (dataset_id);

